/** Реальні твори (без оглядової теми «сучасний літературний процес»). */
export const NMT_REAL_WORKS = NMT_WORKS.filter((w) => w.genre !== 'оглядова тема');

/** Твори НМТ, згруповані за розділами програми. */
export const NMT_BY_SECTION = NMT_SECTIONS.map((section) => ({
  section,
  works: NMT_WORKS.filter((w) => w.section === section),
}));

/** Пари «герой → твір» для завдань на відповідність і для тренажера. */
export const NMT_HEROES = NMT_WORKS.flatMap((w) =>
  (w.heroes ?? []).map((hero) => ({ hero, title: w.title, author: w.author, slug: w.slug }))
);

/** Пари «рядок → твір». */
export const NMT_LINES = NMT_WORKS.flatMap((w) =>
  (w.lines ?? []).map((line) => ({ line, title: w.title, author: w.author, slug: w.slug }))
);

/**
 * Імена, що трапляються в кількох творах («мати», «Мотря», «Катерина»…).
 * Як питання «з якого твору» вони не годяться — правильних відповідей кілька,
 * зате саме на них найлегше спіймати себе на помилці в тесті.
 */
export const NMT_AMBIGUOUS_HEROES = (() => {
  const byName = new Map<string, { title: string; author?: string; slug: string }[]>();
  for (const h of NMT_HEROES) {
    const list = byName.get(h.hero) ?? [];
    list.push({ title: h.title, author: h.author, slug: h.slug });
    byName.set(h.hero, list);
  }
  return [...byName.entries()]
    .filter(([, works]) => works.length > 1)
    .map(([hero, works]) => ({ hero, works }))
    .sort((a, b) => b.works.length - a.works.length || a.hero.localeCompare(b.hero, 'uk'));
})();
